import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const shader = readFileSync(new URL('../frontend/js/viewer.js', import.meta.url), 'utf8');
const stl = readFileSync(new URL('../frontend/js/stl.js', import.meta.url), 'utf8');
assert.match(stl, /color: '#dee1e3'/);
assert.match(shader, /float diffuse = 0\.50/);
assert.match(shader, /baseLinear = pow\(clamp\(uColor/);
assert.match(shader, /vec3 steel = pow\(clamp\(linearSteel, 0\.0, 1\.0\), vec3\(1\.0 \/ 2\.2\)\)/);
assert.match(shader, /0\.06 \* silhouette/);
assert.match(shader, /float softbox = pow/);
assert.match(shader, /gl_FragColor = vec4\(surface, 1\.0\)/);
assert.doesNotMatch(shader, /0\.27 \* silhouette/);
const norm = v => { const m = Math.hypot(...v); return v.map(n=>n/m); };
const dot = (a,b) => a.reduce((total,n,i)=>total+n*b[i],0);
const key = norm([-.47,.83,.31]);
const fill = norm([.81,.32,-.51]);
const back = norm([-.26,-.39,-.88]);
const light = n => .50+.34*Math.max(0,dot(n,key))+.16*Math.max(0,dot(n,fill))+.08*Math.max(0,dot(n,back))+.06*(n[1]*.5+.5);
const gray = n => 255*Math.pow(Math.pow(222/255,2.2)*light(n),1/2.2);
assert.ok(gray([0,-1,0])>160,'even down-facing steel must not be charcoal');
assert.ok(gray([0,1,0])>205,'upward faces must be pale silver');
assert.ok(gray([0,1,0])-gray([0,-1,0])<60,'studio illumination should avoid extreme contrast');
console.log('Studio steel shader: ambient brightness, sRGB, softbox and preserved opaque output verified.');
